PRAGMA foreign_keys = ON;

-- SQLite development schema derived from the nine MSM/MSA Oracle business tables.
-- Oracle-only core authentication/RBAC/API objects are intentionally excluded.
-- This metadata table is SQLite-specific and does not count as a business table.
CREATE TABLE "schema_metadata" (
    "key" TEXT PRIMARY KEY,
    "value" TEXT NOT NULL
);

CREATE TABLE "MSM_MACHINE_DEPARTMENT" (
    "ID" INTEGER PRIMARY KEY,
    "DEPARTMENT_ID" TEXT NOT NULL UNIQUE,
    "DEPARTMENT_NAME" TEXT NOT NULL,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "CREATE_DATE_UNIX" INTEGER
);

-- The Oracle FK to MES_CORE_MKHC.USERS is omitted because core tables are out of scope.
CREATE TABLE "MSM_USER_PERMISSION" (
    "ID" INTEGER PRIMARY KEY,
    "USER_NAME" TEXT NOT NULL UNIQUE,
    "HAS_PERMISSION" TEXT NOT NULL DEFAULT 'N',
    "CREATE_DATE" TEXT NOT NULL,
    "EDIT_DATE" TEXT
);

CREATE TABLE "MSM_PLAN_FILE" (
    "ID" INTEGER PRIMARY KEY,
    "MONTH" INTEGER DEFAULT 1,
    "YEAR" INTEGER DEFAULT 2026,
    "MONTH_ATTACHMENT" TEXT,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "CREATE_DATE_UNIX" INTEGER
);

CREATE TABLE "MSM_TRACE_DIAGRAM" (
    "ID" INTEGER PRIMARY KEY,
    "CUSTOMER_ID" TEXT NOT NULL UNIQUE,
    "CUSTOMER_NAME" TEXT NOT NULL,
    "TRACE_DIAGRAM_ATTACHMENT" TEXT,
    "CREATE_DATE_UNIX" INTEGER,
    "EDIT_DATE_UNIX" INTEGER,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT
);

CREATE TABLE "MSM_MACHINE" (
    "MACHINE_NAME" TEXT NOT NULL,
    "MODEL" TEXT,
    "SERIAL_NUMBER" TEXT,
    "PIC" TEXT,
    "DEPARTMENT_ID" TEXT REFERENCES "MSM_MACHINE_DEPARTMENT" ("DEPARTMENT_ID"),
    "CALIBRATOR" TEXT,
    "LAST_CALIBRATION" INTEGER DEFAULT 0,
    "NEXT_CALIBRATION" INTEGER DEFAULT 0,
    "CALIBRATION_STATUS" TEXT DEFAULT 'Not due yet',
    "INSPECT_CYCLE" INTEGER DEFAULT 12,
    "SPEC" TEXT,
    "PRECISION" TEXT,
    "MAKER" TEXT,
    "CALIBRATE_SHEET" TEXT DEFAULT 'N',
    "ABNORMAL_SHEET" TEXT DEFAULT 'N',
    "APPLIED_STANDARD" TEXT,
    "NOTE" TEXT,
    "STATUS" TEXT DEFAULT 'Active',
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "ID" INTEGER PRIMARY KEY,
    "REGISTERED_DATE" INTEGER,
    "MACHINE_ID" TEXT NOT NULL UNIQUE,
    "PURPOSE" TEXT,
    "IS_MSA" TEXT DEFAULT 'N',
    "IMG_URL" TEXT,
    "IS_ARCHIVE" TEXT DEFAULT 'N',
    "NEXT_DUE_DATE" INTEGER DEFAULT 0,
    "PROJECT_NAME" TEXT,
    "MACHINE_ATTACHMENT" TEXT
);

CREATE TABLE "MSM_USER_EMAIL" (
    "ID" INTEGER PRIMARY KEY,
    "USER_NAME" TEXT REFERENCES "MSM_USER_PERMISSION" ("USER_NAME"),
    "EMAIL" TEXT NOT NULL,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "CREATE_DATE_UNIX" INTEGER,
    "SEND_EMAIL" TEXT DEFAULT 'Y'
);

CREATE TABLE "MSM_CALIB_JUDGE" (
    "ID" INTEGER PRIMARY KEY,
    "CALIBRATION_UNIT" TEXT,
    "CALIBRATION_DATE" INTEGER DEFAULT 0,
    "MANAGER_ID" TEXT,
    "CALIB_ATTACHMENT" TEXT,
    "CALIB_RECORD_SHEET" TEXT,
    "NOTE_CALIB" TEXT,
    "EFFECTIVE" TEXT DEFAULT 'Y',
    "RESCHEDULE_DATE" INTEGER DEFAULT 0,
    "APPROVER_ID" TEXT,
    "NOTE_JUDGE" TEXT,
    "JUDGE_ATTACHMENT" TEXT,
    "EDIT_DATE_UNIX" INTEGER,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "IS_DRAFT" TEXT DEFAULT 'N',
    "NEXT_CALIBRATION_HISTORY" INTEGER DEFAULT 0,
    "MACHINE_ID" TEXT REFERENCES "MSM_MACHINE" ("MACHINE_ID")
);

CREATE TABLE "MSA_MACHINE" (
    "ID" INTEGER PRIMARY KEY,
    "MACHINE_ID" TEXT NOT NULL UNIQUE REFERENCES "MSM_MACHINE" ("MACHINE_ID"),
    "MACHINE_NAME" TEXT,
    "DEPARTMENT_ID" TEXT REFERENCES "MSM_MACHINE_DEPARTMENT" ("DEPARTMENT_ID"),
    "CHARACTERISTICS" TEXT,
    "MANAGER_ID" TEXT,
    "MEASUREMENT_SAMPLE" TEXT,
    "PRD_SAMPLE" TEXT,
    "PRD_SAMPLE_METHOD" TEXT,
    "DATA_TYPE" TEXT DEFAULT 'Variable',
    "BIAS" TEXT DEFAULT 'N',
    "LINEARITY" TEXT DEFAULT 'N',
    "STABILITY" TEXT DEFAULT 'N',
    "GAGE_RR" TEXT DEFAULT 'Y',
    "IS_GO" TEXT DEFAULT 'N',
    "OTHER" TEXT,
    "NEW_PRD" TEXT DEFAULT 'N',
    "PERIODIC" INTEGER DEFAULT 12,
    "NOTE" TEXT,
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "CREATE_DATE_UNIX" INTEGER,
    "LINK_MSM" TEXT DEFAULT 'Y',
    "IS_ARCHIVE" TEXT DEFAULT 'N',
    "YEAR" INTEGER DEFAULT 2026,
    "IS_PERIODIC" TEXT DEFAULT 'Y'
);

CREATE TABLE "MSA_JUDGE" (
    "MACHINE_ID" TEXT REFERENCES "MSA_MACHINE" ("MACHINE_ID"),
    "MACHINE_NAME" TEXT,
    "PRD_SAMPLE" TEXT,
    "CHARACTERISTICS" TEXT,
    "DATA_TYPE" TEXT DEFAULT 'Variable',
    "DEPARTMENT_ID" TEXT REFERENCES "MSM_MACHINE_DEPARTMENT" ("DEPARTMENT_ID"),
    "OBJECT" TEXT,
    "PLAN_DATE_UNIX" TEXT,
    "RESULT_DATE_UNIX" TEXT,
    "CONCLUSION" TEXT,
    "IS_JUDGE_OK" TEXT DEFAULT 'OK',
    "CREATE_DATE" TEXT,
    "EDIT_DATE" TEXT,
    "CREATE_DATE_UNIX" INTEGER,
    "GAGE_RR_ATTACHMENT" TEXT,
    "YEAR" INTEGER DEFAULT 2026,
    "ID" INTEGER PRIMARY KEY
);

