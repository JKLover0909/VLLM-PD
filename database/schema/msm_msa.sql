CREATE INDEX "IDX_MSM_MACHINE_NEXT_CALIBRATION" ON "MSM_MACHINE" ("NEXT_CALIBRATION");
CREATE INDEX "IDX_MSM_CALIB_MACHINE_DATE" ON "MSM_CALIB_JUDGE" ("MACHINE_ID", "CALIBRATION_DATE");
CREATE INDEX "IDX_MSM_CALIB_EFFECTIVE_DRAFT" ON "MSM_CALIB_JUDGE" ("EFFECTIVE", "IS_DRAFT");
CREATE INDEX "IDX_MSA_MACHINE_DEPARTMENT" ON "MSA_MACHINE" ("DEPARTMENT_ID", "IS_ARCHIVE");
